static void _gc_execute_sequence(seq_op *seq, uint16_t len) {
    uint16_t i;
    for (i = 0; i < len; i++) {
        seq_op *op = &seq[i];
        switch (op->type) {
        case CMD_WRITE:
            DM6300B_spi_write(op->addr, op->val);
            break;
        case CMD_READ:
            DM6300B_spi_read(op->addr);
            break;
        case CMD_DELAY_US:
            wait_us(op->addr);
            break;
        default:
            break;
        }
    }
}

static int32_t _gc_auxadc_read_sum(uint8_t aux_idx) {
    uint8_t i;
    uint8_t val_h, val_l;
    uint16_t addr_h = gc_auxadc_data_h[aux_idx];
    uint16_t addr_l = gc_auxadc_data_l[aux_idx];
    int32_t sum = 0;

    for (i = 0; i < 20; i++) {
        DM6300B_spi_write(addr_h, 0x80);
        wait_us(1);
        val_h = DM6300B_spi_read(addr_h) & 0x03;
        val_l = DM6300B_spi_read(addr_l);
        DM6300B_spi_write(addr_h, 0x00);

        /* 10-bit signed conversion */
        sum += (int32_t)((((int16_t)((val_h << 8) | val_l)) ^ 0x200) - 0x200);
    }

    return sum;
}

int8_t gc_read_temperature(void) {
    uint8_t coef;
    uint8_t val;
    int32_t sum_nswap;
    int32_t sum_swap;
    int32_t rslt;
    int32_t temp25_to_mv;
    int32_t temp;

    _gc_execute_sequence(temp_setup_sequence, TEMP_SETUP_LEN);

    coef = DM6300B_spi_read(0x095);

    val = DM6300B_spi_read(0xD2E);
    val &= ~0x10;
    DM6300B_spi_write(0xD2E, val);

    sum_nswap = _gc_auxadc_read_sum(0);

    wait_us(10);

    _gc_execute_sequence(temp_swap_mode_sequence, TEMP_SWAP_LEN);
    sum_swap = _gc_auxadc_read_sum(0);

    _gc_execute_sequence(temp_cleanup_sequence, TEMP_CLEANUP_LEN);

    rslt = (sum_nswap - sum_swap) / 20;

    if (coef == 0)
        temp25_to_mv = 585;
    else
        temp25_to_mv = (int32_t)coef + 500;

    temp = 25 + ((rslt - temp25_to_mv) * 16435) / 32768;

    if (temp > 127)
        temp = 127;
    else if (temp < -60)
        temp = -60;

    return (int8_t)temp;
}

uint16_t gc_read_vctrl(void) {
    uint8_t val;
    int32_t sum_nswap;
    int32_t sum_swap;
    int32_t rslt;

    _gc_execute_sequence(vctrl_setup_sequence, VCTRL_SETUP_LEN);

    val = DM6300B_spi_read(0xD2E);
    val &= ~0x01;
    DM6300B_spi_write(0xD2E, val);

    sum_nswap = _gc_auxadc_read_sum(1);

    wait_us(10);

    _gc_execute_sequence(vctrl_swap_mode_sequence, VCTRL_SWAP_LEN);
    sum_swap = _gc_auxadc_read_sum(1);

    _gc_execute_sequence(vctrl_cleanup_sequence, VCTRL_CLEANUP_LEN);

    rslt = (sum_nswap - sum_swap) / 20;

    return (uint16_t)rslt;
}

void gc_read_scap(void) {
    uint8_t scap_h, scap_l;

    scap_h = DM6300B_spi_read(0x022);
    scap_l = DM6300B_spi_read(0x023);

    gc_scap_value[RF_FREQ] = ((uint16_t)scap_h << 8) | scap_l;
}

void gc_write_scap(void) {
    DM6300B_spi_write(0x647, (uint8_t)(gc_scap_value[RF_FREQ] >> 8));
    DM6300B_spi_write(0x648, (uint8_t)(gc_scap_value[RF_FREQ] & 0xFF));
}

static void gc_adjust_scap(uint16_t vctrl) {
    uint16_t scap;
    scap = gc_scap_value[RF_FREQ];

    if (vctrl <= SCAP_MIN)
        scap += 3;
    else if (vctrl >= SCAP_MAX)
        scap -= 3;

    gc_scap_value[RF_FREQ] = scap;
    gc_write_scap();
}

