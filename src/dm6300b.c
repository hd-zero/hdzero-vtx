const uint8_t lut_tx_pa_gain_0x729 = 0x40;

static int8_t gc_tx_pa_gain_reg_set(uint8_t pa_index) {
    const uint16_t addr[10] = {0x71E, 0x71F, 0x722, 0x723, 0x724, 0x725, 0x726, 0x727, 0x728, 0x729};
    uint8_t val[10];
    uint8_t i;
    int8_t ret = 0;

#ifdef _DEBUG_GC
    if (pa_index > 8) {
        debugf("\r\npa_index out of range");
    }
#endif

    val[0] = lut_tx_pa_gain_0x71E;
    val[1] = lut_tx_pa_gain_0x71F;
    val[2] = lut_tx_pa_gain_0x722[pa_index];
    val[3] = lut_tx_pa_gain_0x723[pa_index];
    val[4] = lut_tx_pa_gain_0x723[pa_index];
    val[5] = lut_tx_pa_gain_0x725[pa_index];
    val[6] = lut_tx_pa_gain_0x726[pa_index];
    val[7] = lut_tx_pa_gain_0x727[pa_index];
    val[8] = lut_tx_pa_gain_0x728;
    val[9] = (RF_BW == BW_17M) ? 0x40 : 0x00; // lut_tx_pa_gain_0x729;

    for (i = 0; i < 10; i++) {
        DM6300B_spi_write(addr[i], val[i]);
    }
    return ret;
}

static uint8_t cur_gain_index = 6;
static uint8_t cur_digital_gain = 0x1E;
void gc_tx_gain_set(uint8_t gain_index) {
    uint8_t bb_index = 0;
    uint8_t pa_index = 0;

    gain_index = GC_GAIN_IDX_MAX - gain_index;

    if (gain_index <= 5) {
        bb_index = gain_index;
        pa_index = 0;
    } else if (gain_index <= 29) {
        pa_index = (gain_index - 3) / 3;
        bb_index = gain_index - pa_index * 3;
    } /*else {
        pa_index = 8;
        bb_index = gain_index - 24;
    }*/
#ifdef _DEBUG_GC
    debugf("\r\nSetting TX gain: gain_index=%bd, bb_index=%bd, pa_index=%bd", gain_index, bb_index, pa_index);
#endif
    gc_tx_bb_gain_reg_set(bb_index);
    gc_tx_pa_gain_reg_set(pa_index);
}
