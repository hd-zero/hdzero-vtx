void DM6300B_SetPower(uint8_t pwr, uint8_t freq, uint8_t offset) {
    int16_t p;

    if (freq >= FREQ_NUM)
        freq = 0;

    if (pwr == POWER_MAX + 1) { // PIT MODE
        gc_tx_gain_set(GC_GAIN_PIT);
    } else {

        p = table_power[freq][pwr] + offset; // tab and offset

#ifndef _RF_CALIB
        if (RF_POWER == 0 && pwr == 0) { // fine tuning in vtx menu

            if (offset_25mw_real() <= 3)
                p += offset_25mw_real();
            else if (p < (offset_25mw_real() - 3))
                p = 0;
            else
                p = p + 3 - offset_25mw_real();
        }
#endif

        if (p > GC_GAIN_IDX_MAX)
            p = GC_GAIN_IDX_MAX;
        else if (p < 0)
            p = 0;

        gc_tx_gain_set((uint8_t)p);

#ifdef _DEBUG_MODE
        debugf("\r\nDM6300B_SetPower: pwr=%x, freq=%x, offset=%x, P=%d", (uint16_t)pwr, (uint16_t)freq, (uint16_t)offset, (uint16_t)p);
#endif
    }
}

void DM6300B_SetChannel(uint8_t ch) {
    if (ch >= FREQ_NUM)
        ch = 0;

    gc_tx_lo_set(ch);
}

